// Regenerates src/lib/scriptUtilTypes.generated.js from the util.* function
// list embedded in ScriptNode.description inside sample-meta.json.
// Run with: node scripts/gen-util-dts.js
const fs = require('fs');
const path = require('path');

const metaPath = path.join(__dirname, '../src/meta/sample-meta.json');
const outPath = path.join(__dirname, '../src/lib/scriptUtilTypes.generated.js');

const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
const desc = meta.nodes.ScriptNode.description;

// Only match "NN) util.name(" when it starts a line (ignoring leading
// whitespace) -- the description text also contains mid-sentence
// cross-references like "(예: 0015) util.channel_number() 와 동일한 함수" that
// must NOT be treated as new entries.
const headerRe = /(?:^|\n)[ \t]*(\d{1,3})\)[ \t]*util\.([A-Za-z_][A-Za-z0-9_]*)[ \t]*\(/g;

const headers = [];
let hm;
while ((hm = headerRe.exec(desc)) !== null) {
  const numStart = hm.index + hm[0].indexOf(hm[1]);
  const openParenIndex = hm.index + hm[0].length - 1; // index of the '('
  headers.push({ num: hm[1], name: hm[2], numStart, openParenIndex });
}

function findMatchingClose(str, openIdx) {
  let depth = 0;
  for (let i = openIdx; i < str.length; i++) {
    if (str[i] === '(') depth++;
    else if (str[i] === ')') {
      depth--;
      if (depth === 0) return i;
    }
  }
  return -1;
}

function splitTopLevel(str) {
  if (!str.trim()) return [];
  const parts = [];
  let depth = 0;
  let cur = '';
  for (const ch of str) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) {
      parts.push(cur.trim());
      cur = '';
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

const asciiIdent = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/;

const entries = [];
for (let i = 0; i < headers.length; i++) {
  const h = headers[i];
  const closeIdx = findMatchingClose(desc, h.openParenIndex);
  const paramsRaw = desc.slice(h.openParenIndex + 1, closeIdx);
  const rawParams = splitTopLevel(paramsRaw);
  const paramNames = rawParams.map((p, idx) => (asciiIdent.test(p) ? p : `arg${idx + 1}`));

  const bodyStart = closeIdx + 1;
  const bodyEnd = i + 1 < headers.length ? headers[i + 1].numStart : desc.length;
  let body = desc.slice(bodyStart, bodyEnd);
  // trim a leading ':' from "func(...) : description"
  body = body.replace(/^\s*:\s*/, '').trim();

  entries.push({ num: h.num, name: h.name, rawParams, paramNames, body });
}

function jsdocEscape(s) {
  return s.replace(/\*\//g, '*\\/').trim();
}

function wrapJsdocLines(text) {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => ` * ${jsdocEscape(l)}`)
    .join('\n');
}

const out = [];
out.push('// AUTO-GENERATED from sample-meta.json ScriptNode.description (util.* functions).');
out.push('// Regenerate via `node scripts/gen-util-dts.js` if the meta description changes — do not hand-edit.');
out.push('declare namespace util {');

for (const r of entries) {
  const paramDocs = r.rawParams
    .map((raw, idx) => (raw === r.paramNames[idx] ? ` * @param ${r.paramNames[idx]}` : ` * @param ${r.paramNames[idx]} ${jsdocEscape(raw)}`))
    .join('\n');
  const bodyDoc = wrapJsdocLines(r.body) || ' * (설명 없음)';
  out.push('  /**');
  out.push(bodyDoc);
  if (paramDocs) out.push(paramDocs);
  out.push('   */');
  out.push(`  function ${r.name}(${r.paramNames.map((p) => `${p}?: any`).join(', ')}): any;`);
  out.push('');
}

out.push('}');

const dts = out.join('\n');

// Escape for embedding inside a JS template literal.
const escaped = dts.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const moduleSource = `// AUTO-GENERATED by scripts/gen-util-dts.js — do not hand-edit.
// Source: src/meta/sample-meta.json -> nodes.ScriptNode.description (util.* functions)
export const SCRIPT_UTIL_DTS = \`${escaped}\`;
`;

fs.writeFileSync(outPath, moduleSource, 'utf8');
console.log(`Wrote ${entries.length} util.* declarations to ${path.relative(process.cwd(), outPath)}`);
