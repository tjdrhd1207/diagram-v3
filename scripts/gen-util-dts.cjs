// Regenerates src/lib/scriptUtilTypes.generated.js from the util.* function
// list in designer.meta.json's `utilFunctions` array (label/insertText/documentation
// — already structured, no text-scraping needed).
// Run with: node scripts/gen-util-dts.cjs
const fs = require('fs');
const path = require('path');

const metaPath = path.join(__dirname, '../src/meta/designer.meta.json');
const outPath = path.join(__dirname, '../src/lib/scriptUtilTypes.generated.js');

const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
const utilFunctions = meta.utilFunctions || [];

const asciiIdent = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/;

// insertText looks like "name(param1, param2)" — pull the param list out of it.
function parseParamNames(insertText) {
  const match = insertText.match(/\(([^)]*)\)/);
  if (!match || !match[1].trim()) return [];
  return match[1]
    .split(',')
    .map((s) => s.trim())
    .map((p, idx) => (asciiIdent.test(p) ? p : `arg${idx + 1}`));
}

function jsdocEscape(s) {
  return s.replace(/\*\//g, '*\\/').trim();
}

function wrapJsdocLines(text) {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => ` * ${jsdocEscape(l)}`)
    .join('\n');
}

const out = [];
out.push('// AUTO-GENERATED from designer.meta.json utilFunctions.');
out.push('// Regenerate via `node scripts/gen-util-dts.cjs` if the meta changes — do not hand-edit.');
out.push('declare namespace util {');

for (const fn of utilFunctions) {
  const paramNames = parseParamNames(fn.insertText);
  const bodyDoc = wrapJsdocLines(fn.documentation || '') || ' * (설명 없음)';
  out.push('  /**');
  out.push(bodyDoc);
  out.push('   */');
  out.push(`  function ${fn.label}(${paramNames.map((p) => `${p}?: any`).join(', ')}): any;`);
  out.push('');
}

out.push('}');

const dts = out.join('\n');

// Escape for embedding inside a JS template literal.
const escaped = dts.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const moduleSource = `// AUTO-GENERATED by scripts/gen-util-dts.cjs — do not hand-edit.
// Source: src/meta/designer.meta.json -> utilFunctions
export const SCRIPT_UTIL_DTS = \`${escaped}\`;
`;

fs.writeFileSync(outPath, moduleSource, 'utf8');
console.log(`Wrote ${utilFunctions.length} util.* declarations to ${path.relative(process.cwd(), outPath)}`);
